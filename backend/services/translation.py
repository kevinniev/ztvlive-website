# Translation cache (in-memory, can be moved to Redis for production)
translation_cache: Dict[str, str] = {}

def get_cache_key(text: str, target_lang: str) -> str:
    """Generate cache key for translation"""
    # Use SHA-256 instead of MD5 for better security
    return hashlib.sha256(f"{text}:{target_lang}".encode()).hexdigest()

def get_ui_text(key: str, lang: str = "en") -> str:
    """Get pre-translated UI text"""
    if lang in UI_TRANSLATIONS and key in UI_TRANSLATIONS[lang]:
        return UI_TRANSLATIONS[lang][key]
    # Fallback to English
    return UI_TRANSLATIONS.get("en", {}).get(key, key)

def get_all_ui_texts(lang: str = "en") -> Dict[str, str]:
    """Get all UI translations for a language"""
    if lang in UI_TRANSLATIONS:
        return UI_TRANSLATIONS[lang]
    return UI_TRANSLATIONS.get("en", {})

async def translate_text(text: str, target_lang: str, source_lang: str = "en") -> str:
    """Translate text using AI - with caching"""
    if not text or target_lang == source_lang:
        return text
    
    # Check cache
    cache_key = get_cache_key(text, target_lang)
    if cache_key in translation_cache:
        return translation_cache[cache_key]
    
    try:
        import os
        from emergentintegrations.llm.chat import LlmChat, UserMessage
        
        api_key = os.environ.get('EMERGENT_LLM_KEY', '')
        if not api_key:
            logger.warning("EMERGENT_LLM_KEY not set, using fallback")
            return text
        
        chat = LlmChat(
            api_key=api_key,
            session_id=f"translate_{target_lang}_{hash(text) % 10000}",
            system_message=f"You are a translator. Translate text from {source_lang} to {target_lang}. Return ONLY the translation, nothing else."
        ).with_model("openai", "gpt-5.2")
        
        response = await chat.send_message(UserMessage(text=text))
        translated = response.strip() if response else text
        
        # Cache the result
        translation_cache[cache_key] = translated
        
        return translated
    except Exception as e:
        logger.error(f"Translation error: {e}")
        return text  # Return original on error

async def normalize_answer_to_english(answer: str, source_lang: str) -> str:
    """Normalize an answer to English for matching purposes"""
    if not answer or source_lang == "en":
        return answer.lower().strip()
    
    # Check cache
    cache_key = get_cache_key(f"norm:{answer}", "en")
    if cache_key in translation_cache:
        return translation_cache[cache_key]
    
    try:
        import os
        from emergentintegrations.llm.chat import LlmChat, UserMessage
        
        api_key = os.environ.get('EMERGENT_LLM_KEY', '')
        if not api_key:
            return answer.lower().strip()
        
        chat = LlmChat(
            api_key=api_key,
            session_id=f"normalize_{hash(answer) % 10000}",
            system_message="You are a translator. Translate to English. Return ONLY one simple English word or short phrase, lowercase."
        ).with_model("openai", "gpt-5.2")
        
        response = await chat.send_message(UserMessage(text=f"Translate from {source_lang}: {answer}"))
        normalized = response.strip().lower() if response else answer.lower()
        
        # Cache the result
        translation_cache[cache_key] = normalized
        
        return normalized
    except Exception as e:
        logger.error(f"Normalization error: {e}")
        return answer.lower().strip()

async def translate_question(question: str, target_lang: str) -> str:
    """Translate a question to target language"""
    if target_lang == "en":
        return question
    return await translate_text(question, target_lang, "en")

async def translate_answer(answer: str, target_lang: str, source_lang: str = "en") -> str:
    """Translate an answer for display"""
    if target_lang == source_lang:
        return answer
    return await translate_text(answer, target_lang, source_lang)

def detect_language_from_code(lang_code: str) -> str:
    """Get full language code from browser language"""
    if not lang_code:
        return "en"
    
    # Handle codes like "en-US", "fr-FR", etc.
    base_code = lang_code.split("-")[0].lower()
    
    if base_code in SUPPORTED_LANGUAGES:
        return base_code
    
    return "en"  # Default to English

